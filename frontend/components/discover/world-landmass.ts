// Curated low-poly world landmass (equirectangular, W=1000 H=500).
// Hand-tuned, dependency-free: no tiles, no third-party requests.
// Coordinates follow GlobalMap project(): x=((lng+180)/360)*W, y=((90-lat)/180)*H.
export interface Landmass {
  id: string;
  label: string | null;
  labelX: number;
  labelY: number;
  d: string;
}

const W = 1000;
const H = 500;

const px = (lng: number, lat: number): [number, number] => [
  ((lng + 180) / 360) * W,
  ((90 - lat) / 180) * H,
];

const path = (rings: Array<Array<[number, number]>>): string =>
  rings
    .map((ring) => {
      const [first, ...rest] = ring.map(([lng, lat]) => px(lng, lat));
      const line = rest
        .map(([x, y]) => `L${x.toFixed(1)},${y.toFixed(1)}`)
        .join("");
      return `M${first[0].toFixed(1)},${first[1].toFixed(1)}${line}Z`;
    })
    .join("");

